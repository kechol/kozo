import { parseArgs } from "node:util";

// Usage: bun run scripts/formula.ts --version 1.2.3 --sums release/SHA256SUMS.txt > kozo.rb

const targets = [
  { os: "macos", cpu: "arm", target: "darwin-arm64" },
  { os: "macos", cpu: "intel", target: "darwin-x64" },
  { os: "linux", cpu: "arm", target: "linux-arm64" },
  { os: "linux", cpu: "intel", target: "linux-x64" },
] as const;

/**
 * The Homebrew formula of a release: one archive per platform from the GitHub Release, each
 * with its checksum from the release's SHA256SUMS.txt, which must list all four.
 */
export function formula(version: string, sums: string): string {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`${version} is not a stable version`);
  const checksums = new Map(
    sums
      .split("\n")
      .map((line) => line.trim().split(/\s+/))
      .filter((fields): fields is [string, string] => fields.length === 2)
      .map(([sum, file]) => [file.replace(/^\*/, ""), sum]),
  );
  const archive = (target: string) => {
    const file = `kozo-${version}-${target}.tar.gz`;
    const sum = checksums.get(file);
    if (!sum || !/^[0-9a-f]{64}$/.test(sum))
      throw new Error(`SHA256SUMS.txt has no checksum of ${file}`);
    return [
      `      url "https://github.com/kechol/kozo/releases/download/v${version}/${file}"`,
      `      sha256 "${sum}"`,
    ];
  };
  const platform = (os: "macos" | "linux") => [
    `  on_${os} do`,
    ...targets
      .filter((entry) => entry.os === os)
      .flatMap((entry) => [`    on_${entry.cpu} do`, ...archive(entry.target), "    end"]),
    "  end",
  ];
  return [
    "# Generated by kozo's release workflow from the GitHub Release; do not edit by hand.",
    "class Kozo < Formula",
    '  desc "Personal software factory that runs on your own machine"',
    '  homepage "https://github.com/kechol/kozo"',
    `  version "${version}"`,
    '  license "MIT"',
    "",
    ...platform("macos"),
    ...platform("linux"),
    "",
    "  def install",
    '    bin.install "kozo", "kozod"',
    "  end",
    "",
    "  def caveats",
    "    <<~EOS",
    "      On Linux, kozod confines the gates with bubblewrap: install the bwrap command and let",
    "      it create user namespaces. Start with `kozo admin init`, then `kozo up`.",
    "    EOS",
    "  end",
    "",
    "  test do",
    '    assert_match version.to_s, shell_output("#{bin}/kozo --version")',
    "  end",
    "end",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const { values } = parseArgs({
    options: { version: { type: "string" }, sums: { type: "string" } },
  });
  if (!values.version || !values.sums) throw new Error("formula needs --version and --sums");
  process.stdout.write(formula(values.version, await Bun.file(values.sums).text()));
}
